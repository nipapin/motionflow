export async function rewriteCommit(Agent, { apiKey, cwd, commitMessage, recentSummaries = [] }) {
  // Custom system prompts require separate Cursor access; standard prompts work
  // with ordinary user API keys. Keep commit data separate from instructions.
  const recent = recentSummaries.filter(text => typeof text === "string").slice(0, 4).map(text => text.slice(0, 300));
  const result = await Agent.prompt(`${rewriteInstructions}\n\nДанные коммита (JSON):\n${JSON.stringify({ commitMessage: commitMessage.slice(0, 1200), recentSummaries: recent })}`, {
    apiKey,
    model: {
      id: "composer-2.5",
      params: [{ id: "fast", value: "false" }],
    },
    tools: [],
    local: { cwd, settingSources: [], enableAgentRetries: false },
  });
  if (result.status !== "finished" || typeof result.result !== "string" || !result.result.trim()) {
    throw new Error("Cursor returned no commit translation");
  }
  return result.result.trim().slice(0, 600);
}
